<BR>
<A NAME="crab"><H2 ALIGN=CENTER>CRABS</H2></A> 
<P ALIGN=LEFT>
<IMG ALIGN=LEFT HSPACE=10 SRC="$ktini{zoographics}/d6crab.gif" WIDTH=154 HEIGHT=154>
A crab walks sideways instead of straight ahead, like most animals. A hard
shell that covers its body helps protect it.  However, in order to grow, a
crab must shed its shell. After shedding, it is soft-bodied and very
vulnerable.  Once its new shell is hard and strong, the crab is ready to
face the world again.
</p>
<BR CLEAR="ALL">
<BR>
<BR>
<A NAME="seahorse"><H2 ALIGN=CENTER>SEAHORSES</H2></A>
<P ALIGN=LEFT>
<IMG ALIGN=LEFT HSPACE=10 SRC="$ktini{zoographics}/d6seahor.gif" WIDTH=154 HEIGHT=154>
A seahorse swims in an upright position. Unlike most animals, the male
seahorse gives birth.  The male has a pouch on its stomach in which
the female places her eggs.  After hatching, the young seahorses stay inside  
the pouch for ten days.  A male seahorse can give birth to as many as 
600 young at one time.
</P> <BR CLEAR="ALL">
<br><br>

<A NAME="shark"><H2 ALIGN=CENTER>SHARKS</H2></A>
<P ALIGN=LEFT>
<IMG ALIGN=LEFT HSPACE=10 SRC="$ktini{zoographics}/d6shark.gif" WIDTH=154 HEIGHT=154>
Most sharks eat fish, sea lions, sea birds, and dolphins.  They are very
efficient hunters and have been nicknamed "eating machines" and "super
predators."  They use a combination of sight, smell, and a form of sonar 
to hunt their prey.
</P> <BR CLEAR="ALL">
<br><br>
<A NAME="starfish"><H2 align=center>STARFISH</H2></A>
<P ALIGN=LEFT>
<IMG ALIGN=LEFT HSPACE=10 SRC="$ktini{zoographics}/d6starfi.gif" WIDTH=154 HEIGHT=154>
There are many types of starfish, also known as "sea stars," in the
ocean.
They can have as few as five arms or as many as forty. If a starfish loses
an arm, it will grow a new one.  The starfish's mouth is located on the
underside of its body.  
</p> <br clear="all">
