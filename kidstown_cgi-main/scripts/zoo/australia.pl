<A NAME="kangaroo"><H2 ALIGN=CENTER>KANGAROOS</H2></A>
<P ALIGN=LEFT>
<IMG ALIGN=LEFT HSPACE=10 SRC="$ktini{zoographics}/d6kanga.gif" HEIGHT="154" WIDTH="154">
Kangaroos stand tall by balancing on their big hind feet and thick tail.   
They can move very quickly by jumping in long leaps.   A young
kangaroo is called a "joey."  </P>
<BR CLEAR="ALL">
<BR>
<BR>


<A NAME="koala"><H2 ALIGN=CENTER>KOALA BEARS</H2></A> 
<P ALIGN=LEFT>
<IMG ALIGN=LEFT HSPACE=10 SRC="$ktini{zoographics}/d6koala.gif" HEIGHT="154" WIDTH="154">
Koala bears look like teddy bears come to life.   They only eat the
leaves of a few trees that live in Australia.   Because the leaves are not
very nutritious, the little bears have to move slowly to conserve
energy.   They spend a lot of time sleeping. </P> <BR CLEAR="ALL">
<BR>
<BR>


<A NAME="croc"><H2 ALIGN=CENTER>CROCODILES</H2></A>
<P ALIGN=LEFT>
<IMG ALIGN=LEFT HSPACE=10 SRC="$ktini{zoographics}/d6croc.gif" HEIGHT="154" WIDTH="154">
The crocodile is a fierce animal that will attack any animal that comes 
near it.   Although clumsy on land, it is an excellent
swimmer.  It spends much of its time drifting quietly under the
surface of the water with only its eyes and nose showing.
</P>
<BR CLEAR="ALL">
<BR>
<BR>


<A NAME="reef"><H2 ALIGN=CENTER>GREAT BARRIER REEF </H2></A>
<P ALIGN=LEFT>
<IMG ALIGN=LEFT HSPACE=10 SRC="$ktini{zoographics}/d6coral.gif" HEIGHT="154 WIDTH="154>
The Great Barrier Reef is a coral reef.   Coral reefs are made of many 
tiny animals.   As these animals grow, they build mini-fortresses around
themselves.   As the animals multiply, their fortresses join to
form large structures in the ocean.   Coral reefs provide food and shelter
to many brightly colored fish that live in the sea. </P> <BR
