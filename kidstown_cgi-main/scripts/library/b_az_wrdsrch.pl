In search of the legendary <B>CITIES OF CIBOLA</B>, in 1540 Francisco
Vasquez
de <B>CORONADO</B> ventures northward from <B>MEXICO</B> into the
territory we today call Arizona. One of his scouting parties discovers one
of the seven natural wonders, the <B>GRAND CANYON</B>.&nbsp;</LI>

<LI>
In 1821 Arizona passes from <B>SPANISH</B> to Mexican rule. There is
beaver
trapping along the <B>SANTA FE TRAIL</B>, and among the trappers are
<B>KIT CARSON</B> and <B>JEDEDIAH SMITH</B>.&nbsp;</LI>

<LI>
Through the Treaty of <B>GUADALUPE HIDALGO</B> and the <B>GADSDEN
PURCHASE</B>,
Arizona becomes a U.S. territory.&nbsp;</LI>

<LI>
In 1881 on October 26th, Wyatt Earp, his 2 brothers, and Doc Holliday gun
down 3 of the Clanton gang in the <B>GUNFIGHT</B> at the<B> O.K.
CORRAL</B>.&nbsp;</LI>

<LI>
A little over a hundred years ago, the fighting between the Native American
Indians and the U.S. government ceases with the surrender of the
<B>APACHE</B>
Indians lead by <B>GERONIMO</B>. Today the <B>NAVAJO</B> are the
predominant Native Americans in the state, with a population around a
hundred thousand and land totaling almost nine million acres. The
<B>HOPI</B> and 12 other tribes reside in Arizona, making it the state
with the highest total population and percentage of Native 
Americans.&nbsp;</LI>

<LI>
The last of the <B>FORTY-EIGHT</B> contiguous states admitted into the
<B>UNION</B>,
on February 14th, 1912, <B>ARIZONA</B> has its statehood. Today, in area
it is the 6th largest state and holds the record for second
<B>HOT</B>test with
a temp of 127 degrees registered in Parker, AZ., in 1905.&nbsp;</LI>

<LI>
Arizona's major cities include <B>MESA</B>, <B>PHOENIX</B>, <B>TEMPE</B>,
and <B>TUCSON</B>.&nbsp;</LI>

<LI>
Along with its warm climate, the beautiful and varied landscape has made
Arizona a popular vacation state. Arizona boasts  a range of terrain from
lush pine <B>FOREST</B>s to <B>CACTUS</B>-punctuated <B>DESERT</B>s and 
from
gradually changing plateaus and <B>PLAINS</B> to the mesas, cliffs, and
arches of the <B>GRAND CANYON</B>.&nbsp;</LI>

<LI>
Like many other mountain states, Arizona is rich in mineral deposits.
Arizona mines <B>GOLD</B>, <B>ZINC</B>, <B>URANIUM</B>, and copper. In
fact, Arizona mines so much <B>COPPPER</B> that it accounts for more than
the 49 other states combined.&nbsp;</LI>

<LI>
Arizona has several professional sports teams, including the <B>Suns</B>
and <B>Coyotes</B>. It is also the winter home of many of the Major League
<B>Baseball</B> teams from colder cities.&nbsp;</LI>
