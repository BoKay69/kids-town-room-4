<OL>
<LI>
The capital city of <B>JUNEAU </B>was founded on the Gastineau Channel
by gold miners in 1880.&nbsp;</LI>

<LI>
The three major rivers of Alaska are the <B>YUKON</B>, the <B>TANANA</B>,
and the <B>KUSKOKWIM</B>.&nbsp;</LI>

<LI>
The name Alaska is derived from two native words: the <B>ALEUT</B> word
<I>alaxsxaq</I>, meaning "the object toward which the action of the sea is
directed,"
and the <B>ESKIMO</B> word which has the same meaning,
<B>ALASKA</B>.&nbsp;</LI>

<LI>
<B>MT. MCKINLEY</B>, also known as <B>DENALI</B>, is the highest summit
in North America. It reaches 20,230 ft above sea level.&nbsp;</LI>

<LI>
Alaska is geologically active, with both <B>VOLCANIC</B> activity and
earthquakes commonplace.&nbsp;</LI>

<LI>
A full third of the state lies above the <B>ARCTIC</B> circle and is known
as the <B>NORTH SLOPE</B>.&nbsp;</LI>

<LI>
On 8 August 1728, <B>ST. LAWRENCE ISLAND</B>, which lies off the
northwestern
coast, was discovered by a Dane, <B>VITUS BERING</B>, in the employ of the
<B>Russian</B> Navy.&nbsp;</LI>

<LI>
During WWII, the U.S. government stationed 152,000 troops in Alaska, and
Alaska had the dubious honor of actually being invaded. The
<B>JAPANESE</B>
Imperial Navy made amphibious landings and occupied the islands of
<B>ATTU</B>
and <B>KISKA</B> in the <B>ALEUTIAN</B> chain.&nbsp;</LI>

<LI>
<B>ANCHORAGE</B> was originally founded as a rail construction camp, but
today it is the largest Alaskan city. For comparison, it has roughly the
same population as Colorado Springs, Colorado or the capital of Minnesota,
St. Paul.&nbsp;</LI>

<LI>
With the exceptions of <B>POTATOES</B>es, <B>CABBAGE</B>s, and
<B>CARROT</B>s,
Alaska imports most of its agricultural needs. Its main wealth is in mineral
resources, including rich deposits of <B>GOLD</B>, <B>COPPER</B>,
<B>COAL</B>,
<B>OIL</B>, and natural gas. Alaska also has a profitable timber trade
and <B>FISHING</B> industry, exporting vast quantities of lumber,
<B>SALMON</B>,
<B>CRAB</B>, and <B>HERRING</B>.&nbsp;</LI>
